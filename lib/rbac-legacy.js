export function legacyPermissionsForRole(role) {
  const r = String(role || "").toLowerCase();
  if (r === "admin") {
    return ALL_MAHAVERSE;
  }
  if (r === "client") {
    return [
      PERM.NAV_DASHBOARD,
      PERM.NAV_CLIENTS,
      PERM.VIEW_DASHBOARD,
      PERM.VIEW_CLIENTS,
      PERM.CLIENTS_READ,
      PERM.CLIENTS_VIEW,
      PERM.CLIENTS_UPDATE,
    ];
  }
  if (r === "planner") {
    return [
      PERM.NAV_SCHEDULING,
      PERM.VIEW_SCHEDULING,
      PERM.SCHEDULING_READ,
      PERM.SCHEDULING_WRITE,
      PERM.SCHEDULING_SESSION_CREATE,
      PERM.SCHEDULING_SESSION_VIEW,
      PERM.SCHEDULING_SESSION_NOTES,
      PERM.SCHEDULING_SESSION_UPDATE,
      PERM.SCHEDULING_SESSION_DELETE,
    ];
  }
  if (r === "parent") {
    return [PERM.NAV_DASHBOARD, PERM.VIEW_DASHBOARD];
  }
  if (r === "biller") {
    return [
      PERM.NAV_DASHBOARD,
      PERM.NAV_CLIENTS,
      PERM.NAV_BILLING,
      PERM.NAV_MANAGE_DATA,
      PERM.VIEW_DASHBOARD,
      PERM.VIEW_CLIENTS,
      PERM.VIEW_BILLING,
      PERM.VIEW_MANAGE_DATA,
      PERM.VIEW_PROVIDER,
      PERM.VIEW_PROVIDER_SERVICE_CODE,
      PERM.VIEW_SERVICE_CODE,
      PERM.VIEW_DIAGNOSIS,
      PERM.CLIENTS_READ,
      PERM.CLIENTS_WRITE,
      PERM.CLIENTS_VIEW,
      PERM.CLIENTS_UPDATE,
      PERM.MANAGE_DATA_READ,
      PERM.MANAGE_DATA_WRITE,
      PERM.MANAGE_DATA_PROVIDER,
      PERM.MANAGE_DATA_PROVIDER_SERVICE,
      PERM.MANAGE_DATA_SERVICE_CODE,
      PERM.MANAGE_DATA_DIAGNOSIS,
      PERM.BILLING_READ,
      PERM.BILLING_WRITE,
      PERM.BILLING_SFTP,
    ];
  }
  if (r === "bcba") {
    return [
      PERM.NAV_SCHEDULING,
      PERM.NAV_CLIENTS,
      PERM.NAV_LAUNCHPAD,
      PERM.NAV_STAFF,
      PERM.VIEW_SCHEDULING,
      PERM.VIEW_CLIENTS,
      PERM.VIEW_LAUNCHPAD,
      PERM.VIEW_STAFF,
      PERM.VIEW_DOMAINS,
      PERM.VIEW_PROGRAMS,
      PERM.VIEW_TARGETS,
      PERM.VIEW_PROMPTS,
      PERM.CLIENTS_READ,
      PERM.CLIENTS_WRITE,
      PERM.CLIENTS_VIEW,
      PERM.STAFF_READ,
      PERM.STAFF_WRITE,
      PERM.SCHEDULING_READ,
      PERM.SCHEDULING_WRITE,
      PERM.SCHEDULING_SESSION_CREATE,
      PERM.SCHEDULING_SESSION_VIEW,
      PERM.SCHEDULING_SESSION_NOTES,
      PERM.SCHEDULING_SESSION_UPDATE,
      PERM.MASTER_DATA_READ,
      PERM.MASTER_DATA_WRITE,
      PERM.MASTER_DATA_DOMAINS,
      PERM.MASTER_DATA_PROGRAMS,
      PERM.MASTER_DATA_TARGETS,
      PERM.MANAGE_DATA_READ,
    ];
  }
  if (r === "rbt") {
    return [
      PERM.NAV_SCHEDULING,
      PERM.NAV_CLIENTS,
      PERM.NAV_LAUNCHPAD,
      PERM.NAV_STAFF,
      PERM.VIEW_SCHEDULING,
      PERM.VIEW_CLIENTS,
      PERM.VIEW_LAUNCHPAD,
      PERM.VIEW_STAFF,
      PERM.CLIENTS_READ,
      PERM.CLIENTS_VIEW,
      PERM.STAFF_READ,
      PERM.SCHEDULING_READ,
      PERM.SCHEDULING_SESSION_VIEW,
      PERM.SCHEDULING_SESSION_NOTES,
    ];
  }
  return legacyPermissionsForRole("rbt");
}
